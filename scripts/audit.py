"""Produce data/coverage.json and COVERAGE.md (Phase A audit table + pilot coverage).
usage: audit.py <data_dir> <inventory.json> <coverage_md_out>"""
import json, sys, collections

data, inv_path, md_out = sys.argv[1:4]
L = lambda n: json.load(open(f"{data}/{n}.json", encoding="utf-8"))
P, M = L("questions_prelims"), L("questions_mains")
Q, links, concepts, queue = L("question_links"), L("concept_links"), L("concepts"), L("review_queue")
qlinks, syl = L("question_links"), L("syllabus")
res, stubs = L("resources"), L("concept_stubs")
inv = json.load(open(inv_path))

cov = {"inputs": inv}
# Prelims
py = collections.Counter(q["year"] for q in P)
cov["prelims"] = {"total": len(P), "years": dict(sorted(py.items())), "answer_status": dict(collections.Counter(q["answer_status"] for q in P)),
                  "flagged": sum(1 for q in P if q["flags"]), "official_key_check": "NOT PERFORMED — answers are as supplied by the third-party compilation",
                  "years_not_100": {y: c for y, c in py.items() if y >= 2011 and c != 100}}
# Mains
rows = []
for y in range(2013, 2027):
    for n in (1, 2, 3, 4):
        paper = f"GS-{n}"
        qs = [q for q in M if q["year"] == y and q["paper"] == paper]
        if not qs and y < 2016:
            rows.append({"year": y, "paper": paper, "status": "MISSING-PAPER", "expected": 20 if n < 4 else None, "parsed": 0, "flagged": 0})
            continue
        rows.append({"year": y, "paper": paper, "status": "imported", "expected": 20 if n < 4 else None, "parsed": len(qs),
                     "flagged": sum(1 for q in qs if any(f.split("(")[0] not in {"marks-derived-from-word-limit", "ocr-wordlimit-normalised", "closed-by-next-number", "text-from-alt-ocr-psm6", "renumbered-by-order", "number-from-marker-group"} for f in q["flags"])),
                     "manual": sum(1 for q in qs if q["verification"].startswith("manually"))})
cov["mains"] = {"total": len(M), "rows": rows}
# Concepts
cnt = collections.Counter(l["concept_id"] for l in qlinks)
unc = L("unclassified_questions")
subs = L("subjects")
cov["concepts"] = {"count": len(concepts), "without_pyq_link": [c["id"] for c in concepts if cnt[c["id"]] == 0],
                   "pyq_links": len(qlinks), "all_links_proposed": all(l["status"] == "proposed" for l in qlinks),
                   "by_subject": {s["id"]: {"title": s["title"], "status": s["status"], "concepts": sum(1 for c in concepts if c["subject"] == s["id"]),
                                            "pyq_links": sum(1 for l in qlinks if l["concept_id"].split("-")[0] == s["id"]),
                                            "prelims_unlinked": len(unc.get(s["id"], []))} for s in subs},
                   "mains_unmatched": {k: len(v) for k, v in unc.items() if k.startswith("mains-")}}
cov["review_queue"] = dict(collections.Counter(x["kind"] for x in queue))
cov["resources"] = {"count": len(res), "by_access": dict(collections.Counter(r["access"] for r in res))}
json.dump(cov, open(f"{data}/coverage.json", "w"), indent=1)

o = ["# Coverage & audit report", "", "Generated by `scripts/audit.py` from the data in `data/`. Nothing here is hand-edited.", "",
     "## 1. Inputs inventoried", "", "| File | Type | Pages | Text layer | Handling |", "|---|---|---|---|---|"]
for i in inv:
    o.append(f"| {i['file']} | {i['type']} | {i['pages']} | {i['text_layer']} | {i['handling']} |")
o += ["", "## 2. Prelims GS-I (supplied compilation)", "",
      f"- Questions parsed: **{len(P)}** (years {min(py)}–{max(py)}). The file itself states 3976 — parsed count matches.",
      f"- Answer status: {cov['prelims']['answer_status']}",
      f"- Answers are **as supplied** by the third-party compilation; **comparison with UPSC official keys was not performed**. Cancelled/ambiguous items are marked, not resolved.",
      f"- Years 2011+ with a count other than 100: {cov['prelims']['years_not_100'] or 'none'}",
      "- Years 1995–2010 parse to 146–150 questions each; no expected count is asserted for them (not verified against UPSC).",
      f"- Questions with any parse flag: {cov['prelims']['flagged']} (see review queue).",
      "- Subject/topic labels are the compiler's, not UPSC's.", "", "| Year | Questions |", "|---|---|"]
o += [f"| {y} | {c} |" for y, c in sorted(py.items())]
o += ["", "## 3. Mains GS-I to GS-IV (downloaded from UPSC, scanned images → OCR)", "",
      "OCR (tesseract, English) was used; Hindi lines were filtered out heuristically. Text is **ocr-unverified**: always check the linked source PDF page. "
      "GS-I to GS-III have exactly 20 questions per paper in this period, so counts are checked against 20. GS-IV structure varies (parts, long case studies), "
      "so no expected count is asserted and several GS-IV case studies are merged into one block (flag `likely-multiple-case-studies-merged`) — **GS-IV is not reliable and needs manual splitting**.", "",
      "| Year | Paper | Status | Expected | Parsed | Needs review | Manually transcribed |", "|---|---|---|---|---|---|---|"]
for r in rows:
    o.append(f"| {r['year']} | {r['paper']} | {r['status']} | {r['expected'] if r['expected'] else 'n/a'} | {r['parsed']} | {r['flagged']} | {r.get('manual', 0)} |")
o += ["", "**2013, 2014 and 2015 Mains papers are not available** on the UPSC previous-question-papers page or its archive and were not downloaded.", "",
      "## 4. Polity pilot", "",
      f"- Concepts authored: **{len(concepts)}** (status `draft-unreviewed`: written by the assistant from general knowledge, not checked against textbooks).",
      f"- Proposed PYQ↔concept links: **{len(qlinks)}** (all `proposed`; keyword/label rules; not human reviewed; precision unmeasured).",
      f"- Concepts with no PYQ link in the supplied data: {cov['concepts']['without_pyq_link'] or 'none'} (they still link to syllabus points).",
      "", "| Subject | Status | Concepts | Proposed PYQ links | Prelims Qs of that label with no link |", "|---|---|---|---|---|"]
for sid, v in cov["concepts"]["by_subject"].items():
    o.append(f"| {v['title']} | {v['status']} | {v['concepts']} | {v['pyq_links']} | {v['prelims_unlinked']} |")
o += ["", f"- Mains questions matching no concept yet (subjects not built): {cov['concepts']['mains_unmatched']}.",
      f"- Resources cataloged: {len(res)} (URLs HTTP-checked on 2026-11-13; NCERT chapter locations and book chapters/editions are **not verified** and are not given).",
      f"- Cross-subject stub targets (not authored yet): {len(stubs)}.",
      f"- Syllabus items extracted from the supplied syllabus.pdf: {len(syl)}.", "",
      "## 5. Review queue", "", f"`data/review_queue.json` — {len(queue)} items: {cov['review_queue']}.", "",
      "## 6. Not done / limitations", "",
      "- Every subject has draft concepts, but none claims to cover its full syllabus.",
      "- Prelims answers not checked against UPSC official keys.",
      "- Prelims questions on aptitude/reasoning, sports, awards, business and other Current Affairs topics are not linked (no concept subject for them).",
      "- No claim of complete ten-year coverage is made.", ""]
open(md_out, "w").write("\n".join(o))
print("ok")
